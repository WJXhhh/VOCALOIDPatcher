"""Measure DRS bit-13 scalar responses to controlled PCM gain and pitch.

All PCM is generated by this script. The report contains aggregate differences
only; no voicebank frame or audio data is read or written.
"""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

from audit_frm2_numeric import D, F, I, P, SHA256, f32
from probe_frm2_batch_outputs import owned_pcm, run as analyze_batch


FEATURE_OFFSETS = {0: 4, 1: 8, 2: 12, 6: 0x1c, 16: 0x218,
                   17: 0x21c, 18: 0x220}


def capture(dll: Path, pcm: list[float], frequency: float,
            pitch_seed: float) -> dict[int, dict[int, float]]:
    holder = []
    summary = analyze_batch(
        dll, 0, 1, "steady", frequency, pitch_seed=pitch_seed,
        pcm_override=pcm,
        setup_observer=lambda native, context: holder.append((native, context)),
    )
    native, context = holder[0]
    track = P.from_address(context + 0xcd0).value
    if not track:
        raise AssertionError("DRS batch returned no feature track")
    result = {}
    regions = P.from_address(track + 0x148).value
    for region_index in range(I.from_address(track + 0x140).value):
        region = P.from_address(regions + 8 * region_index).value
        frames = P.from_address(region + 0x20).value
        for frame_index in range(I.from_address(region + 0x18).value):
            frame = P.from_address(frames + 8 * frame_index).value
            feature = P.from_address(frame + 0x128).value
            if not feature:
                continue
            flags = I.from_address(feature).value
            if any(not flags & (1 << bit) for bit in FEATURE_OFFSETS):
                raise AssertionError("expected bit-13 scalar is missing")
            time = round(D.from_address(frame + 0x48).value * 44100 / 256)
            if time in result:
                raise AssertionError("duplicate feature frame time")
            result[time] = {
                bit: F.from_address(feature + offset).value
                for bit, offset in FEATURE_OFFSETS.items()
            }
    if len(result) != summary["frames"]:
        raise AssertionError("feature frames differ from batch output")
    del native
    return result


def run(dll: Path) -> dict:
    gain_cases = []
    for frequency in (440, 880):
        base = owned_pcm("steady", frequency)
        observations = {
            gain: capture(dll, [f32(value * gain) for value in base],
                          frequency, frequency)
            for gain in (0.5, 1.0, 2.0)
        }
        times = sorted(set.intersection(*(set(rows) for rows in observations.values())))
        if len(times) != 44:
            raise AssertionError("owned gain cases have unexpected frame alignment")
        for gain in (0.5, 2.0):
            reference = observations[1.0]
            altered = observations[gain]
            expected = 2.0 * math.log10(gain)
            residuals = [abs((altered[time][16] - reference[time][16]) - expected)
                         for time in times]
            invariant = {
                str(bit): max(abs(altered[time][bit] - reference[time][bit])
                              for time in times)
                for bit in (0, 1, 6, 18)
            }
            if max(residuals) > 1e-5 or max(invariant.values()) > 1e-5:
                raise AssertionError("gain response differs from the tested relation")
            gain_cases.append({
                "frequency_hz": frequency,
                "gain": gain,
                "compared_frames": len(times),
                "bit16_log_power_shift_max_residual": max(residuals),
                "gain_invariant_field_max_deltas": invariant,
            })

    base = owned_pcm("steady", 440)
    pitch_cases = {seed: capture(dll, base, 440, seed)
                   for seed in (220, 440, 880)}
    times = sorted(set.intersection(*(set(rows) for rows in pitch_cases.values())))
    if len(times) != 44:
        raise AssertionError("owned pitch cases have unexpected frame alignment")
    pitch_response = {}
    for bit in FEATURE_OFFSETS:
        deltas = [max(abs(pitch_cases[220][time][bit] - pitch_cases[440][time][bit]),
                      abs(pitch_cases[880][time][bit] - pitch_cases[440][time][bit]))
                  for time in times]
        pitch_response[str(bit)] = {
            "changed_over_1e_6": sum(value > 1e-6 for value in deltas),
            "max_delta": max(deltas),
        }
    if (pitch_response["16"]["changed_over_1e_6"] != len(times)
            or pitch_response["18"]["changed_over_1e_6"] != len(times)
            or any(pitch_response[str(bit)]["changed_over_1e_6"]
                   for bit in (0, 1, 2, 6))):
        raise AssertionError("pitch-seed dependency differs from observed path")
    return {
        "dse_sha256": SHA256,
        "pcm_origin": "owned 44.1 kHz harmonic signals",
        "gain_cases": gain_cases,
        "pitch_seed_comparison": {
            "signal_hz": 440,
            "seed_hz": [220, 440, 880],
            "compared_frames": len(times),
            "field_responses": pitch_response,
        },
        "scope": "DRS external-pitch mode with controlled PCM; identifies numerical dependencies, not VQM authoring configuration.",
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dll", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    result = run(args.dll)
    args.output.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({
        "gain_cases": len(result["gain_cases"]),
        "gain_frames": sum(row["compared_frames"] for row in result["gain_cases"]),
        "pitch_frames": result["pitch_seed_comparison"]["compared_frames"],
    }))


if __name__ == "__main__":
    main()
